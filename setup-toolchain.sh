#!/usr/bin/env bash
# One-time setup of a local Android SDK toolchain so the build scripts can run
# without Android Studio. Installs the command-line tools plus the SDK packages
# this project needs under ~/android-toolchain and writes env.sh for the build
# scripts to source.
#
# Requires: internet access, a JDK 17+ on PATH, and ~2.5 GB of free disk.
# Easier alternative: just open this project in Android Studio (see README).
set -euo pipefail

TOOLCHAIN="${ANDROID_TOOLCHAIN_DIR:-$HOME/android-toolchain}"
SDK="$TOOLCHAIN/sdk"

# commandlinetools "latest" zip. If this 404s, grab the current URL from
# https://developer.android.com/studio#command-line-tools-only and update it.
CLI_ZIP="commandlinetools-linux-11076708_latest.zip"
CLI_URL="https://dl.google.com/android/repository/${CLI_ZIP}"

mkdir -p "$SDK"

if [ ! -x "$SDK/cmdline-tools/latest/bin/sdkmanager" ]; then
  echo "→ Downloading Android command-line tools…"
  tmp="$(mktemp -d)"
  curl -fL "$CLI_URL" -o "$tmp/$CLI_ZIP"
  unzip -q "$tmp/$CLI_ZIP" -d "$tmp"
  mkdir -p "$SDK/cmdline-tools"
  rm -rf "$SDK/cmdline-tools/latest"
  mv "$tmp/cmdline-tools" "$SDK/cmdline-tools/latest"
  rm -rf "$tmp"
fi

export ANDROID_SDK_ROOT="$SDK"
export ANDROID_HOME="$SDK"
SDKMANAGER="$SDK/cmdline-tools/latest/bin/sdkmanager"

echo "→ Accepting SDK licenses…"
yes | "$SDKMANAGER" --sdk_root="$SDK" --licenses >/dev/null || true

echo "→ Installing platform-tools, platforms;android-35, build-tools;35.0.0…"
"$SDKMANAGER" --sdk_root="$SDK" \
  "platform-tools" \
  "platforms;android-35" \
  "build-tools;35.0.0"

cat > "$TOOLCHAIN/env.sh" <<EOF
# Sourced by build scripts. Generated by setup-toolchain.sh.
export ANDROID_SDK_ROOT="$SDK"
export ANDROID_HOME="$SDK"
export PATH="\$ANDROID_SDK_ROOT/cmdline-tools/latest/bin:\$ANDROID_SDK_ROOT/platform-tools:\$PATH"
EOF

echo "✓ Toolchain ready — env.sh written to $TOOLCHAIN/env.sh"
echo "  Next:  ./build-apk.sh"
